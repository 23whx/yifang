const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const source = read('components/cube/useManualSteps.ts');
const states = [], refs = [];
let stateIndex = 0, refIndex = 0;
const react = {
  useRef(initial) { const i = refIndex++; return refs[i] ??= { current: initial }; },
  useState(initial) { const i = stateIndex++; if (!(i in states)) states[i] = initial; return [states[i], value => { states[i] = value; }]; },
};
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const exportsObject = {};
vm.runInNewContext(output, { exports: exportsObject, require: name => { assert.equal(name, 'react'); return react; } });
const render = () => { stateIndex = 0; refIndex = 0; return exportsObject.useManualSteps(); };
let hook = render();
const played = [];
let resets = 0;
hook.cube.current = { isBusy: () => false, play: token => played.push(token), reset: () => resets++, applyInstant: () => {} };
hook.move('R', 1);
assert.deepEqual(played, [], 'must wait for canvas readiness');
hook.onReady();
hook = render();
hook.move('R', 1);
hook.move('U', 2);
assert.deepEqual(played, ['R'], 'rapid second click must not queue another move');
assert.equal(hook.prepare(), false, 'cannot reset during a pending move');
assert.equal(render().cursor, 0, 'progress must wait for animation');
hook.onBusyChange(true);
hook.onBusyChange(false);
hook = render();
assert.equal(hook.cursor, 1);
assert.equal(hook.busy, false);
hook.onBusyChange(false);
assert.deepEqual(played, ['R'], 'completion must not automatically play another move');
assert.equal(resets, 0, 'completion must not reset the cube');
hook.move('U2', 2);
hook.onBusyChange(true);
hook.onBusyChange(false);
assert.deepEqual(played, ['R', 'U2'], 'a half turn remains a single explicit step');
assert.equal(render().cursor, 2);
assert.equal(exportsObject.describeTurn("R'", true).includes('逆时针'), true);
assert.equal(exportsObject.describeTurn('U2', false).includes('180'), true);
const tutorial = read('components/cube/TutorialPlayer.tsx');
assert.match(tutorial, /\["notation", "cube-first-lesson", "patterns"\]\.includes/);
assert.doesNotMatch(tutorial, /requestAnimationFrame|playAlg|\.scramble\(/);
assert.doesNotMatch(read('components/cube/CubePuzzles.tsx'), /play\(current\.solution\)/);
assert.doesNotMatch(read('components/cube/CubeFirstPractice.tsx'), /\.play\(option\)/);
console.log('PASS: manual moves, readiness, rapid-click guard, completion, no auto-reset, pattern setup, and all three teaching entry points.');
